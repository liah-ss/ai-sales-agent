function getInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'en'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored === 'zh-CN' || stored === 'id' || stored === 'en') return stored
  const browserLanguage = window.navigator.language
  if (browserLanguage.startsWith('zh')) return 'zh-CN'
  if (browserLanguage.startsWith('id')) return 'id'
  return 'en'
}

const initialLocale = getInitialLocale()

export function createAppI18n(locale: Locale = initialLocale) {
  return createI18n({
    legacy: false,
    globalInjection: false,
    locale,
    fallbackLocale: 'en',
    messages,
    flatJson: true,
    missingWarn: false,
    fallbackWarn: false,
  })
}

export const i18n = createAppI18n()

if (typeof document !== 'undefined') {
  document.documentElement.lang = initialLocale
}

function persistLocale(nextLocale: Locale) {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, nextLocale)
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = nextLocale
  }
}

export function normalizeLocale(language: string): Locale | null {
  const normalized = language.toLowerCase()
  if (normalized === 'zh-cn' || normalized === 'zh' || normalized === 'cn') return 'zh-CN'
  if (normalized === 'id' || normalized === 'id-id' || normalized === 'indonesian') return 'id'
  if (normalized === 'en' || normalized === 'en-us' || normalized === 'english') return 'en'
  return null
}

export function useI18n() {
  const composer = useVueI18n({ useScope: 'global' })
  const locale = computed(() => composer.locale.value as Locale)
  const localeLabel = computed(() => localeLabels[locale.value])

  function setLocale(nextLocale: Locale) {
    composer.locale.value = nextLocale
    persistLocale(nextLocale)
  }

  function t(key: string, fallback = key, variables?: Record<string, string>) {
    const translated = composer.t(key, variables ?? {})
    return translated === key && fallback ? fallback : translated
  }

  function languageLabel(language: Locale) {
    return localeLabels[language]
  }

  function languageOptions(languages: string[] = ['en', 'zh-CN', 'id']) {
    const config = useRuntimeConfig()
    const normalized = languages
      .map(language => normalizeLocale(language))
      .filter((language): language is Locale => Boolean(language))
      .filter(language => !(config.public.hideZhCn && language === 'zh-CN'))
    return [...new Set(normalized.length ? normalized : ['en' as Locale, 'id' as Locale])]
  }

  return {
    locale,
    localeLabel,
    setLocale,
    t,
    languageLabel,
    languageOptions,
  }
}
